  @moduledoc """
  Grafana's unit ids and the formatter each one uses, as listed in Grafana's
  `packages/grafana-data/src/valueFormats/categories.ts`.

  Every id maps to a spec `GrafExTerm.Format.format/3` knows how to apply:

    * `{:fixed, unit, as_prefix?}` — the number, then (or before) `unit`
    * `{:si, unit, offset}` — SI-prefixed `unit` (`k`, `M`, `m`, `µ`, …), `offset`
      shifting the base prefix
    * `{:binary, unit, offset}` — binary-prefixed `unit` (`Ki`, `Mi`, …)
    * `{:scaled, factor, suffixes}` — the number divided by powers of `factor`
    * `{:count, symbol}` — `K`/`M`/`B`/`T` scaling, then `symbol`
    * `{:currency, symbol, as_suffix?}` — `K`/`M`/`B`/`T` scaling with a symbol
    * `{:bool, true_text, false_text}`
    * `{:duration, interval}`, `{:date, style, today_time_only?}`
    * an atom naming one of Grafana's own formatters (`:s`, `:ms`, `:percent`, …)
  """

